#!/usr/bin/env bash
# Install (or reinstall) the morning briefing as a macOS LaunchAgent:
#
#   scripts/launchd/install.sh     # install or update
#   scripts/launchd/uninstall.sh   # stop and remove
#
# Runs daily at 07:30; override with
#   JARVIS_BRIEFING_HOUR=6 JARVIS_BRIEFING_MINUTE=45 scripts/launchd/install.sh
# A run missed while the Mac sleeps starts once when it wakes. A Mac that is
# off at that time skips the day, and the GUI keeps the last briefing.
#
# Mechanics copied from Personal Intelligence scripts/launchd/install.sh.
# Paths are resolved at install time, so nothing machine-specific is
# committed. Rerun after moving the repo or reinstalling uv, or after a Node
# upgrade moves the readwise command.
set -euo pipefail

LABEL="com.marcobraun.jarvis.morning-briefing"
REPO_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
UV_BIN="$(command -v uv || true)"
READWISE_BIN="$(command -v readwise || true)"
AGENTS_DIR="$HOME/Library/LaunchAgents"
LOG_DIR="$HOME/Library/Logs/JARVIS"
DOMAIN="gui/$(id -u)"
HOUR="${JARVIS_BRIEFING_HOUR:-7}"
MINUTE="${JARVIS_BRIEFING_MINUTE:-30}"

if [[ -z "$UV_BIN" ]]; then
  echo "uv not found on PATH" >&2
  exit 1
fi

# launchd starts with a bare PATH. readwise is a Node script: its directory
# has to be on PATH for both the command and the node that runs it.
ENV_PATH="$(dirname "$UV_BIN"):/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin"
if [[ -n "$READWISE_BIN" ]]; then
  ENV_PATH="$(dirname "$READWISE_BIN"):$ENV_PATH"
else
  echo "readwise not found on PATH: the Reading section will say not available" >&2
fi

mkdir -p "$LOG_DIR" "$AGENTS_DIR"
cat > "$AGENTS_DIR/$LABEL.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by $REPO_DIR/scripts/launchd/install.sh; edit that script, not this file. -->
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>$LABEL</string>
    <key>ProgramArguments</key>
    <array>
        <string>$UV_BIN</string>
        <string>run</string>
        <string>--directory</string>
        <string>$REPO_DIR</string>
        <string>jarvis</string>
        <string>run-job</string>
        <string>morning-briefing</string>
    </array>
    <key>WorkingDirectory</key>
    <string>$REPO_DIR</string>
    <key>EnvironmentVariables</key>
    <dict>
        <key>PATH</key>
        <string>$ENV_PATH</string>
        <key>PYTHONUNBUFFERED</key>
        <string>1</string>
    </dict>
    <key>StartCalendarInterval</key>
    <dict>
        <key>Hour</key>
        <integer>$HOUR</integer>
        <key>Minute</key>
        <integer>$MINUTE</integer>
    </dict>
    <key>ProcessType</key>
    <string>Background</string>
    <key>StandardOutPath</key>
    <string>$LOG_DIR/morning-briefing.log</string>
    <key>StandardErrorPath</key>
    <string>$LOG_DIR/morning-briefing.log</string>
</dict>
</plist>
PLIST
plutil -lint "$AGENTS_DIR/$LABEL.plist" >/dev/null

# Replace a running instance so the new definition takes effect.
launchctl bootout "$DOMAIN/$LABEL" 2>/dev/null || true
launchctl bootstrap "$DOMAIN" "$AGENTS_DIR/$LABEL.plist"

printf 'Installed %s (daily at %02d:%02d)\n' "$LABEL" "$HOUR" "$MINUTE"
echo "  log:      $LOG_DIR/morning-briefing.log"
echo "  run now:  launchctl kickstart $DOMAIN/$LABEL"
